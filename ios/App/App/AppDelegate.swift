        // Override point for customization after application launch.
        return true
    }

    // MASKED: the app switcher shows a plain screen, not the wallet (the recovery phrase, balances)
    private var privacyCover: UIView?

    func applicationWillResignActive(_ application: UIApplication) {
        guard privacyCover == nil, let window = self.window else { return }
        let cover = UIView(frame: window.bounds)
        cover.autoresizingMask = [.flexibleWidth, .flexibleHeight]
        cover.backgroundColor = UIColor(red: 11 / 255, green: 11 / 255, blue: 12 / 255, alpha: 1)
        if let logo = UIImage(named: "Splash") {
            let view = UIImageView(image: logo)
            view.contentMode = .scaleAspectFill
            view.frame = cover.bounds
            view.autoresizingMask = [.flexibleWidth, .flexibleHeight]
            cover.addSubview(view)
        }
        window.addSubview(cover)
        privacyCover = cover
    }

    func applicationDidEnterBackground(_ application: UIApplication) {
